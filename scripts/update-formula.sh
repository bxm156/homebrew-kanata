#!/bin/sh
# Write Formula/kanata.rb for a signed kanata release.
#
# Usage: scripts/update-formula.sh <version> <sha256 of the release tarball> [revision]
#
# Called by .github/workflows/build-kanata.yml after it publishes the release,
# so the formula always points at an asset that exists. The whole file is
# regenerated each time; edit the template below, not Formula/kanata.rb.
#
# revision is the rebuild number for the same kanata version (default 0). It
# must use the same naming as the workflow: rebuilds get a _N suffix.

set -eu

VERSION="${1:?usage: update-formula.sh <version> <sha256> [revision]}"
SHA256="${2:?usage: update-formula.sh <version> <sha256> [revision]}"
REVISION="${3:-0}"
REPO="${GITHUB_REPOSITORY:-bxm156/kanata-launch}"

SUFFIX=""
REVISION_LINE=""
if [ "$REVISION" != "0" ]; then
  SUFFIX="_$REVISION"
  # Homebrew's own "revision" makes `brew upgrade` pick up a rebuild of the
  # same upstream version.
  REVISION_LINE="
  revision $REVISION"
fi

cd "$(dirname "$0")/.."
mkdir -p Formula

cat > Formula/kanata.rb <<EOF
# Generated by scripts/update-formula.sh. Do not edit by hand.
class Kanata < Formula
  desc "Keyboard remapper, built from upstream source and signed in CI"
  homepage "https://github.com/jtroo/kanata"
  url "https://github.com/${REPO}/releases/download/kanata-v${VERSION}${SUFFIX}/kanata-${VERSION}${SUFFIX}-arm64-apple-darwin.tar.gz"
  version "${VERSION}"
  sha256 "${SHA256}"
  license "LGPL-3.0-only"${REVISION_LINE}

  depends_on arch: :arm64
  depends_on :macos

  def install
    # Prebuilt and already code-signed in CI. Do not re-sign it here: the
    # macOS privacy grant follows the CI signature.
    bin.install "kanata"
  end

  # Declarative post-install steps; Homebrew has deprecated \`def post_install\`.
  post_install_steps do
    # macOS ties a privacy grant to the real path of a binary, and Homebrew's
    # real path changes with every version (Cellar/kanata/<version>/...).
    # Symlinks such as bin/kanata do not help, because macOS resolves them.
    # So keep a copy at a path that never changes and run kanata from there.
    # It is named kanata-signed so it is not mistaken for an upstream build.
    #
    # The copy goes straight into #{HOMEBREW_PREFIX}/bin as a real file, next
    # to the symlinks Homebrew manages there. Homebrew does not track it and
    # formulae have no uninstall hook, so \`brew uninstall\` leaves it behind;
    # delete it by hand if you remove kanata.
    #
    # Remove the old copy first so the new one is a fresh file: overwriting a
    # signed binary in place can make macOS reject its signature.
    remove "bin/kanata-signed", base: :homebrew_prefix
    copy "bin/kanata", "bin/kanata-signed", target_base: :homebrew_prefix
  end

  def caveats
    <<~EOS
      Run kanata from this path, which stays the same across upgrades:
        #{HOMEBREW_PREFIX}/bin/kanata-signed

      Grant that file Input Monitoring and Accessibility once, in
      System Settings -> Privacy & Security. The grant follows the signature,
      so it should not need repeating after an upgrade.
    EOS
  end

  test do
    system bin/"kanata", "--version"
  end
end
EOF

echo "Wrote Formula/kanata.rb for kanata ${VERSION} (revision ${REVISION})"
