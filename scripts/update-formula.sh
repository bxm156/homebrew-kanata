#!/bin/sh
# Write Formula/kanata.rb for a signed kanata release.
#
# Usage: scripts/update-formula.sh <version> <sha256 of the release tarball>
#
# Called by .github/workflows/build-kanata.yml after it publishes the release,
# so the formula always points at an asset that exists. The whole file is
# regenerated each time; edit the template below, not Formula/kanata.rb.

set -eu

VERSION="${1:?usage: update-formula.sh <version> <sha256>}"
SHA256="${2:?usage: update-formula.sh <version> <sha256>}"
REPO="${GITHUB_REPOSITORY:-bxm156/kanata-launch}"

cd "$(dirname "$0")/.."
mkdir -p Formula

cat > Formula/kanata.rb <<EOF
# Generated by scripts/update-formula.sh. Do not edit by hand.
class Kanata < Formula
  desc "Keyboard remapper, built from upstream source and signed for kanata-launch"
  homepage "https://github.com/jtroo/kanata"
  url "https://github.com/${REPO}/releases/download/kanata-v${VERSION}/kanata-${VERSION}-arm64-apple-darwin.tar.gz"
  version "${VERSION}"
  sha256 "${SHA256}"
  license "LGPL-3.0-only"

  depends_on arch: :arm64
  depends_on :macos

  def install
    # Prebuilt and already code-signed in CI. Do not re-sign it here: the
    # launcher only accepts the CI signature.
    bin.install "kanata"
  end

  test do
    system bin/"kanata", "--version"
  end
end
EOF

echo "Wrote Formula/kanata.rb for kanata ${VERSION}"
